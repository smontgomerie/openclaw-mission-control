#!/usr/bin/env node
/**
 * Generate / apply Better Auth's Postgres migration for the dedicated
 * `better_auth` schema (Alembic in `public` must never manage these tables).
 *
 * Modes (npm scripts):
 *   npm run db:migration:generate   -> writes better-auth/migrations/0000_initial.sql
 *   npm run db:migration:apply      -> runs that SQL against BETTER_AUTH_DATABASE_URL
 *
 * The options below mirror `buildMigrationsConfig` in `src/lib/better-auth.ts`
 * (the source of truth for schema-affecting options: user.additionalFields.hd
 * + jwt + apiKey plugins). If you change schema-affecting options there,
 * update this script and regenerate.
 */
import { readFileSync } from "node:fs";
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const SCHEMA = "better_auth";

// getMigrations introspects a live Postgres (information_schema) to emit
// Postgres-flavoured DDL, so generation needs a reachable database.
const generateUrl =
  process.env.BETTER_AUTH_DATABASE_URL ??
  "postgresql://postgres:postgres@127.0.0.1:5432/mission_control";
const { Pool } = await import("pg");
const pool = new Pool({ connectionString: generateUrl });

const options = {
  secret: "migration-generation-only-secret",
  baseURL: "http://localhost:3000",
  database: pool,
  emailAndPassword: { enabled: false },
  user: {
    additionalFields: {
      hd: { type: "string", required: false },
    },
  },
  socialProviders: {
    google: { enabled: true, clientId: "x", clientSecret: "x" },
  },
  plugins: [],
};

function qualifySchema(sql) {
  // Qualify every table reference with the dedicated schema so the DDL
  // lands in better_auth.* regardless of the executing session's search_path.
  return sql
    .replace(/create table (?!"better_auth"\.)/gi, `create table "${SCHEMA}". `)
    .replace(/(create index \"[^\"]+\" )on (?!\"better_auth\".\s)/gi, (m) =>
      m.replace(/on /i, `on "${SCHEMA}".`),
    )
    .replace(/"better_auth"\. /g, '"better_auth".');
}

const mode = process.argv[2] ?? "generate";

if (mode === "generate") {
  const { getMigrations } = await import("better-auth/db");
  const { jwt, apiKey } = await import("better-auth/plugins");
  options.plugins = [
    jwt({
      jwt: {
        issuer: "http://localhost:3000",
        audience: "http://localhost:3000",
      },
    }),
    apiKey({ defaultPrefix: "mc_" }),
  ];
  const { compileMigrations } = await getMigrations(options);
  const body = qualifySchema(await compileMigrations());
  const out = [
    `-- Better Auth migration 0000 (generated by scripts/generate-better-auth-migration.mjs)`,
    `-- Tables live in the dedicated \`${SCHEMA}\` schema; Alembic (public schema)` +
      ` must not manage or trip over them.`,
    `CREATE SCHEMA IF NOT EXISTS ${SCHEMA};`,
    `-- Unqualified references (session -> user, apikey -> user, ...) resolve to`,
    `-- ${SCHEMA} via this session-level search_path; apply the file in a single session.`,
    `SET search_path TO ${SCHEMA}, public;`,
    body.trim(),
    ``,
  ].join("\n");
  const target = path.resolve(
    __dirname,
    "..",
    "better-auth",
    "migrations",
    "0000_initial.sql",
  );
  mkdirSync(path.dirname(target), { recursive: true });
  await pool.end();
  writeFileSync(target, out);
  console.log(`wrote ${path.relative(process.cwd(), target)}`);
} else if (mode === "apply") {
  const { Pool } = await import("pg");
  const url = process.env.BETTER_AUTH_DATABASE_URL;
  if (!url) {
    console.error(
      "BETTER_AUTH_DATABASE_URL is required (plain postgresql:// URL to the `db` service).",
    );
    process.exit(1);
  }
  const sqlPath = path.resolve(
    __dirname,
    "..",
    "better-auth",
    "migrations",
    "0000_initial.sql",
  );
  const sql = readFileSync(sqlPath, "utf8");
  const pool = new Pool({ connectionString: url });
  try {
    // One session so `CREATE SCHEMA` + table DDL share a single connection.
    const client = await pool.connect();
    try {
      await client.query(sql);
      const tables = await client.query(
        `SELECT tablename FROM pg_tables WHERE schemaname = 'better_auth' ORDER BY tablename`,
      );
      console.log(
        `applied ${sqlPath} to ${url.split("@").pop() ?? url} (tables: ${tables.rows.map((r) => r.tablename).join(", ")})`,
      );
    } finally {
      client.release();
    }
  } finally {
    await pool.end();
  }
} else {
  console.error(`unknown mode: ${mode} (use generate | apply)`);
  process.exit(1);
}
